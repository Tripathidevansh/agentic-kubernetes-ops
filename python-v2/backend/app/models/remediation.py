"""
Remediation Data Models for Safe GitOps Operations.

Defines schemas for declarative YAML patches, risk classification, strict
human-in-the-loop approvals, provenance tracking, and post-remediation verification plans.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
import uuid

from pydantic import BaseModel, Field, field_validator, model_validator


class RiskLevel(str, Enum):
    """Risk classification for automated Kubernetes remediations."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class ApprovalStatus(str, Enum):
    """Lifecycle state of human operator approval."""
    PENDING = "PENDING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class ProposalStatus(str, Enum):
    """Actionability status of a remediation proposal."""
    ACTIONABLE = "ACTIONABLE"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    REJECTED_SAFETY_VIOLATION = "REJECTED_SAFETY_VIOLATION"


class ProposalProvenance(str, Enum):
    """Explicit origin of a remediation proposal."""
    GEMINI_AGENT = "GEMINI_AGENT"
    DETERMINISTIC_FALLBACK = "DETERMINISTIC_FALLBACK"
    DETERMINISTIC_ENGINE = "DETERMINISTIC_ENGINE"


class YamlPatch(BaseModel):
    """Structured representation of a proposed GitOps YAML modification."""
    target_kind: str = Field(..., description="Kubernetes resource kind (e.g. Deployment, Pod, StatefulSet)")
    target_name: str = Field(..., description="Name of the target resource")
    target_namespace: Optional[str] = Field(default=None, description="Target namespace")
    diff: str = Field(..., description="Unified diff or declarative delta showing proposed change")
    patch_content: Dict[str, Any] = Field(
        default_factory=dict,
        description="Structured dictionary representation of the patch"
    )

    @field_validator("target_kind", "target_name", "diff")
    @classmethod
    def validate_non_empty(cls, v: str, info) -> str:
        if not v or not v.strip():
            raise ValueError(f"Field '{info.field_name}' must not be empty")
        return v.strip()


class HumanApproval(BaseModel):
    """Strict human-in-the-loop review and approval record."""
    status: ApprovalStatus = Field(default=ApprovalStatus.PENDING)
    reviewer: Optional[str] = Field(default=None, description="Operator identity or username")
    reviewed_at: Optional[str] = Field(default=None, description="ISO timestamp of review decision")
    comments: Optional[str] = Field(default=None, description="Operator justification or feedback")


class VerificationPlan(BaseModel):
    """Post-remediation automated verification plan."""
    target_phase: str = Field(default="Running", description="Expected Pod phase post-remediation")
    expected_conditions: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of expected status conditions (e.g. Ready=True)"
    )
    negative_assertions: List[str] = Field(
        default_factory=list,
        description="Negative conditions that must NOT occur (e.g. CrashLoopBackOff, OOMKilled)"
    )
    check_interval_seconds: int = Field(default=5, ge=1, le=60, description="Polling interval in seconds")
    timeout_seconds: int = Field(default=60, ge=5, le=300, description="Verification timeout in seconds")


class RemediationProposal(BaseModel):
    """Complete remediation proposal generated by the Planning stage."""
    proposal_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    target_workload: str = Field(..., description="Name of the workload or Pod investigated")
    target_kind: str = Field(default="Pod", description="Resource kind (Deployment, Pod, StatefulSet, etc.)")
    target_name: str = Field(default="", description="Name of the target resource to patch")
    target_namespace: str = Field(default="k8s-agent-demo", description="Target namespace")
    status: ProposalStatus = Field(default=ProposalStatus.ACTIONABLE, description="Actionability status")
    can_remediate: bool = Field(default=True, description="Whether a safe, valid patch could be generated")
    insufficient_evidence_reason: Optional[str] = Field(
        default=None,
        description="Detailed explanation if remediation cannot safely be proposed"
    )
    patch: Optional[YamlPatch] = Field(default=None, description="Declarative patch details and unified diff")
    justification: str = Field(..., description="Technical explanation and root cause alignment")
    risk_level: RiskLevel = Field(default=RiskLevel.MEDIUM, description="Risk level assessment")
    requires_approval: bool = Field(
        default=True,
        description="Strict safety guardrail: must be True for production deployments"
    )
    approval: Optional[HumanApproval] = Field(
        default=None,
        description="Operator approval record"
    )
    verification_plan: Optional[VerificationPlan] = Field(
        default=None,
        description="Automated post-fix verification plan"
    )
    provenance: ProposalProvenance = Field(
        default=ProposalProvenance.DETERMINISTIC_FALLBACK,
        description="Origin: GEMINI_AGENT, DETERMINISTIC_FALLBACK, or DETERMINISTIC_ENGINE"
    )
    model_metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Provider and model metadata (model name, temperature, etc.) without credentials"
    )
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @field_validator("target_workload", "justification")
    @classmethod
    def validate_non_empty_strings(cls, v: str, info) -> str:
        if not v or not v.strip():
            raise ValueError(f"Field '{info.field_name}' must not be empty")
        return v.strip()

    @model_validator(mode="after")
    def validate_actionability_and_patch(self) -> "RemediationProposal":
        if not self.target_name:
            self.target_name = self.target_workload

        if self.can_remediate:
            if not self.patch:
                raise ValueError("RemediationProposal with can_remediate=True must include a valid patch.")
        else:
            if self.status == ProposalStatus.ACTIONABLE:
                self.status = ProposalStatus.INSUFFICIENT_EVIDENCE
            if not self.insufficient_evidence_reason:
                self.insufficient_evidence_reason = (
                    "Remediation cannot safely be proposed due to insufficient evidence or risk of masking failure."
                )
        return self


class BatchProposalItem(BaseModel):
    """Structured proposal item within a batch remediation response from Gemini."""
    item_id: str = Field(..., description="Unique diagnosis identifier matching input item_id")
    resource_name: Optional[str] = Field(default=None, description="Affected resource name (e.g. pod-name/container)")
    status: str = Field(default="ACTIONABLE", description="ACTIONABLE or INSUFFICIENT_EVIDENCE")
    can_remediate: bool = Field(default=True, description="Whether a safe, valid patch could be generated")
    insufficient_evidence_reason: Optional[str] = Field(
        default=None,
        description="Detailed explanation if remediation cannot safely be proposed"
    )
    justification: str = Field(default="", description="Technical explanation and root cause alignment")
    risk_level: str = Field(default="MEDIUM", description="Risk classification: LOW, MEDIUM, HIGH")
    diff: Optional[str] = Field(default=None, description="Unified diff or declarative delta showing proposed change")
    patch_content: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Structured dictionary representation of the patch"
    )


class BatchRemediationResponse(BaseModel):
    """Batch container for multi-incident remediation proposals from Gemini."""
    proposals: List[BatchProposalItem] = Field(
        default_factory=list,
        description="List of proposed remediations matching each input diagnosis"
    )
